"""Stage 7: pipeline verification - record counts at every stage + SQL checks.

Prints the table that goes into the report and writes docs/pipeline_summary.md.
Exit code 1 if any consistency check fails.
"""
import logging
import re
import sqlite3
import sys

from src import config


def run_sql_file(conn: sqlite3.Connection) -> str:
    text = (config.SQL_DIR / "verification_queries.sql").read_text(encoding="utf-8")
    out = []
    for block in [b.strip() for b in text.split(";") if b.strip()]:
        title = re.match(r"--\s*(Q\d+:[^\n]*)", block)
        query = "\n".join(l for l in block.splitlines() if not l.strip().startswith("--"))
        cur = conn.execute(query)
        rows = cur.fetchall()
        header = [d[0] for d in cur.description]
        out.append(f"{title.group(1) if title else query[:50]}\n  columns: {header}\n"
                   + ("\n".join(f"  {r}" for r in rows[:12]) if rows else "  (0 rows)"))
    return "\n\n".join(out)


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    s = config.load_stats()
    if not config.DB_PATH.exists():
        print("Database not found. Run the loader first.")
        return 1
    with sqlite3.connect(config.DB_PATH) as conn:
        db_rows = conn.execute("SELECT COUNT(*) FROM klines").fetchone()[0]
        sql_report = run_sql_file(conn)

    g = lambda k: s.get(k, 0)
    injected = g("injected_tests") + g("injected_duplicates")
    rows = [
        ("Collected from API", g("collected"), f"{len(config.SYMBOLS)} symbols x {config.LIMIT} candles"),
        ("Injected test records + duplicates", injected,
         f"{g('injected_tests')} invalid tests + {g('injected_duplicates')} duplicates"),
        ("Published to Kafka", g("published"), f"failed: {g('publish_failed')}"),
        ("Consumed from Kafka", g("consumed"), f"corrupted skipped: {g('consumed_corrupted')}"),
        ("Valid (Pandera)", g("valid"), f"{g('duplicates_flagged')} duplicate rows passed on to cleaner"),
        ("Invalid (quarantined)", g("invalid"), f"tests caught by schema: {g('tests_caught_by_schema')}/{g('injected_tests')}"),
        ("After cleaning", g("cleaned"), f"duplicates removed: {g('duplicates_removed')}, dropped (missing): {g('rows_dropped_missing')}"),
        ("Stored in SQLite", db_rows, "COUNT(*) FROM klines"),
    ]
    checks = [
        ("published == collected + injected", g("published") == g("collected") + injected),
        ("no publish failures", g("publish_failed") == 0),
        ("consumed == published", g("consumed") == g("published")),
        ("valid + invalid == consumed", g("valid") + g("invalid") == g("consumed")),
        ("all injected test records caught by schema", g("tests_caught_by_schema") == g("injected_tests")),
        ("cleaned == valid - duplicates - dropped", g("cleaned") == g("valid") - g("duplicates_removed") - g("rows_dropped_missing")),
        ("stored in SQLite == cleaned", db_rows == g("cleaned")),
        ("2nd load inserted 0 rows (idempotent)", s.get("load2_inserted") == 0 and s.get("idempotent") is True),
    ]

    lines = ["| Stage | Count | Comment |", "|---|---|---|"] + [f"| {a} | {b} | {c} |" for a, b, c in rows]
    table = "\n".join(lines)
    check_text = "\n".join(f"[{'OK' if ok else 'FAIL'}] {name}" for name, ok in checks)
    print("\n=== PIPELINE COUNTS ===\n" + table)
    print("\n=== CONSISTENCY CHECKS ===\n" + check_text)
    print("\n=== SQL VERIFICATION ===\n" + sql_report)

    config.DOCS_DIR.mkdir(exist_ok=True)
    (config.DOCS_DIR / "pipeline_summary.md").write_text(
        "# Pipeline summary (generated by src/verify.py)\n\n" + table + "\n\n## Consistency checks\n\n```\n"
        + check_text + "\n```\n\n## SQL verification\n\n```\n" + sql_report + "\n```\n", encoding="utf-8")
    failed = [n for n, ok in checks if not ok]
    if failed:
        print("\nFAILED CHECKS:", failed)
        return 1
    print("\nALL CHECKS PASSED")
    return 0


if __name__ == "__main__":
    sys.exit(main())
